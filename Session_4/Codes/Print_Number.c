#include <stdio.h>

int main() {
    int i;
    for(i = 1; i <= 10; i++) {
        printf("%d ", i);
    }
    return 0;
}
/*
  This program prints numbers from 1 to 10 using a for loop.
  
  - for loop initializes i to 1, checks if i is less than or equal to 10,
    and increments i by 1 in each iteration.
  
  - printf("%d ", i) prints the current value of i followed by a space.
  
*/